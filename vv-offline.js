// vv-offline.js — OFFLINE READING (Harsha 2026-10-22/23): "Save this text for offline" (☰ menu on every reading page) + the
// saved-texts list (★ My library → Offline). Loaded by vv-reader.js on every reading page and by library.html.
// Data: offline.json (written by build_deploy.js §7) = { saved: <cache name>, shell: [[file,bytes,hash]…],
//   texts: { <key>: { title, files: [[file,bytes,hash]…], parts: [{ id, label, files }] } } } — a text = its reading-<key>[-N].html
//   pages + gloss (always saved) + its separately loaded commentary lanes (parts, each optional). Saving puts those + the shared
//   shell into the long-lived <prefix>saved cache, which the service worker (generated by build_deploy.js) reads from when there
//   is no network. Which texts are saved, with which parts and each file's hash, is kept in localStorage (vv_offline:<cache
//   name> — namespaced because the academy and the public site share one origin), so after a deploy refresh() re-downloads only
//   the files whose content changed. Pages the reader merely OPENED are kept too (the service worker's <prefix>rt cache) —
//   that needs nothing here.
// 2026-10-25 (Harsha): the save is a dialog — the reader picks which separate commentaries to include (all ticked by default)
//   and "Search within this text": the search site's engine + this text's index shards (the SAME shards vv-insearch.js picks,
//   via the search site's lib/sv-links.js), stored by absolute URL; the service worker serves them offline.
(function () {
  'use strict';
  if (window.VVOffline) return;
  var BASE = location.href.split('#')[0].split('?')[0].replace(/[^/]*$/, '');
  var SEARCH = new URL('../prasthanatrayi-search/', BASE).href;   // = vv-insearch.js SEARCH, build_deploy.js SEARCH_REL
  var man = null, manP = null;
  function manifest() {
    if (man) return Promise.resolve(man);
    if (!manP) manP = fetch(BASE + 'offline.json', { cache: 'no-cache' }).then(function (r) { if (!r.ok) throw new Error('no offline.json'); return r.json(); })
      .then(function (m) { man = m; return m; }, function (e) { manP = null; throw e; });
    return manP;
  }
  function supported() { return !!(window.caches && navigator.serviceWorker && window.isSecureContext); }
  function lsKey(m) { return 'vv_offline:' + m.saved; }
  function loadIdx(m) { try { return JSON.parse(localStorage.getItem(lsKey(m)) || '{}') || {}; } catch (e) { return {}; } }
  function saveIdx(m, idx) { try { localStorage.setItem(lsKey(m), JSON.stringify(idx)); } catch (e) {} }
  function abs(f) { return /^https?:/.test(f) ? f : BASE + f; }
  function esc(s) { return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
  function textOfPage(m, page) {
    page = page || location.pathname.split('/').pop();
    for (var k in m.texts) if (m.texts[k].files.some(function (r) { return r[0] === page; })) return k;
    return null;
  }
  // the text's opening page: reading-<key>-1.html if it has numbered pages, else its one page (manifest order, else saved index)
  function firstPage(m, key, rec) {
    var pages = (m.texts[key] ? m.texts[key].files.map(function (r) { return r[0]; }) : Object.keys((rec && rec.files) || {})).filter(function (f) { return /^reading-.*\.html$/.test(f); });
    return pages.filter(function (f) { return /-1\.html$/.test(f); })[0] || pages[0] || null;
  }
  function sizeOf(files) { return files.reduce(function (n, r) { return n + r[1]; }, 0); }
  function mb(bytes) { var v = bytes / 1048576; return (v < 10 ? v.toFixed(1) : Math.round(v)) + ' MB'; }
  function lanes(m, key) { return (m.texts[key] && m.texts[key].parts) || []; }
  // the parts a saved entry chose; a save made before parts existed had every lane and no search
  function chosenOf(m, key, rec) { return rec && rec.parts ? rec.parts : lanes(m, key).map(function (p) { return p.id; }); }

  // ---- "Search within this text": the search site's search-meta.json + engine + this text's shards (hashed names) ----
  var L = null, lP = null;
  function svlinks() {
    if (L) return Promise.resolve(L);
    if (window.SVLinks) return Promise.resolve(L = window.SVLinks);
    if (!lP) lP = new Promise(function (ok, ko) { var e = document.createElement('script'); e.src = SEARCH + 'lib/sv-links.js'; e.onload = function () { window.SVLinks ? ok(L = window.SVLinks) : ko(new Error('sv-links')); }; e.onerror = function () { lP = null; ko(new Error('sv-links')); }; document.head.appendChild(e); });
    return lP;
  }
  // → { id: 'search', label, files } or null (no search for this text / search site unreachable). Fixed-name files carry hash ''
  // and are fetched again on every refresh (a cheap revalidation); shards + refidx are content-hashed, so their name is the hash.
  function searchPart(key) {
    return Promise.all([svlinks(), fetch(SEARCH + 'search-meta.json', { cache: 'no-cache' }).then(function (r) { if (!r.ok) throw new Error('search-meta'); return r.json(); })])
      .then(function (res) {
        var ids = res[0].idsFor(key) || [], meta = res[1];
        var shards = meta.shards.filter(function (s) { return ids.indexOf(s.f.replace(/^shards\//, '').replace(/\.[0-9a-f]{10}\.json$/, '')) >= 0; });
        if (!shards.length) return null;
        var files = [[SEARCH + 'search-meta.json', 0, ''], [SEARCH + 'lib/sanskrit-search.js', 70000, ''], [SEARCH + 'lib/sv-links.js', 10000, ''],
          [SEARCH + meta.refidx, meta.refidxB || 0, meta.refidx]].concat(shards.map(function (s) { return [SEARCH + s.f, s.b || 0, s.f]; }));
        return { id: 'search', label: 'Search within this text', files: files };
      }).catch(function () { return null; });
  }
  // every optional part of a text: its lanes + (when available) search
  function partsOf(m, key) {
    return searchPart(key).then(function (sp) { return lanes(m, key).concat(sp ? [sp] : []); });
  }
  // the files a text needs = its own + the chosen parts + the shared shell (fonts, scripts, icons)
  function need(m, key, parts, chosen) {
    var files = m.texts[key].files.concat(m.shell);
    parts.forEach(function (p) { if (chosen.indexOf(p.id) >= 0) files = files.concat(p.files); });
    return files;
  }

  // fetch straight from the network (the x-vv-save header makes the service worker step aside) and store in the saved cache
  function fetchInto(cache, files, onStep) {
    var i = 0, failed = null;
    function worker() {
      if (failed || i >= files.length) return Promise.resolve();
      var r = files[i++];
      return fetch(abs(r[0]), { cache: 'no-cache', headers: { 'x-vv-save': '1' } }).then(function (res) {
        if (!res.ok) throw new Error(r[0].replace(/^.*\//, '') + ': HTTP ' + res.status);
        return cache.put(abs(r[0]), res);
      }).then(function () { if (onStep) onStep(r); return worker(); }, function (e) { failed = e; });
    }
    return Promise.all([worker(), worker(), worker()]).then(function () { if (failed) throw failed; });
  }
  // files of the saved entries other than `except` (a file shared by two texts — the shell — must outlive either)
  function usedElsewhere(idx, except) {
    var still = {}; Object.keys(idx).forEach(function (k) { if (k !== except) Object.keys(idx[k].files || {}).forEach(function (f) { still[f] = 1; }); });
    return still;
  }
  // save (or re-save with a different choice) a text: chosen = the part ids to include; save(key, onProgress) = every part
  function save(key, chosen, onProgress) {
    if (typeof chosen === 'function') { onProgress = chosen; chosen = null; }
    return manifest().then(function (m) {
      return partsOf(m, key).then(function (parts) {
        if (!chosen) chosen = parts.map(function (p) { return p.id; });
        var files = need(m, key, parts, chosen), total = sizeOf(files), done = 0;
        return caches.open(m.saved).then(function (cache) {
          return fetchInto(cache, files, function (r) { done += r[1]; if (onProgress) onProgress(Math.min(done, total), total); }).then(function () {
            var idx = loadIdx(m), h = {}, old = (idx[key] && idx[key].files) || {};
            files.forEach(function (r) { h[r[0]] = r[2]; });
            idx[key] = { title: m.texts[key].title, bytes: total, at: new Date().toISOString(), files: h, parts: chosen };
            saveIdx(m, idx);
            var still = usedElsewhere(idx, key);   // parts the reader just dropped
            return Promise.all(Object.keys(old).filter(function (f) { return !h[f] && !still[f]; }).map(function (f) { return cache.delete(abs(f)); }))
              .then(function () { return idx[key]; });
          });
        });
      });
    });
  }
  function remove(key) {
    return manifest().then(function (m) {
      var idx = loadIdx(m), gone = idx[key]; if (!gone) return;
      delete idx[key]; saveIdx(m, idx);
      var still = usedElsewhere(idx, null);
      return caches.open(m.saved).then(function (cache) {
        return Promise.all(Object.keys(gone.files || {}).filter(function (f) { return !still[f]; }).map(function (f) { return cache.delete(abs(f)); }));
      });
    });
  }
  // saved texts whose first page is really in the cache (the reader may have cleared website data: then forget the entry)
  function list() {
    return manifest().then(function (m) {
      var idx = loadIdx(m), keys = Object.keys(idx);
      return caches.open(m.saved).then(function (cache) {
        return Promise.all(keys.map(function (k) {
          var first = firstPage(m, k, idx[k]);
          return first ? cache.match(abs(first)).then(function (hit) { return hit ? first : null; }) : null;
        }));
      }).then(function (ok) {
        var out = [], changed = false;
        keys.forEach(function (k, i) {
          if (!ok[i]) { delete idx[k]; changed = true; return; }
          var ch = chosenOf(m, k, idx[k]), labels = lanes(m, k).filter(function (p) { return ch.indexOf(p.id) >= 0; }).map(function (p) { return p.label; });
          if (ch.indexOf('search') >= 0) labels.push('search');
          out.push({ key: k, title: idx[k].title, bytes: idx[k].bytes, at: idx[k].at, first: ok[i], includes: labels });
        });
        if (changed) saveIdx(m, idx);
        return out;
      });
    });
  }
  function info(key) {
    return manifest().then(function (m) {
      key = key || textOfPage(m); if (!key || !m.texts[key]) return null;
      var idx = loadIdx(m);
      return { key: key, title: m.texts[key].title, bytes: sizeOf(m.texts[key].files.concat(m.shell)), saved: !!idx[key] };
    });
  }
  // after a deploy: bring every saved text up to date — only files whose content hash changed are fetched again (the search
  // site's fixed-name files always: a revalidation); files a text no longer has are dropped. Online only; quietly in the background.
  var refreshing = null;
  function refresh() {
    if (refreshing || !navigator.onLine) return refreshing || Promise.resolve();
    refreshing = manifest().then(function (m) {
      var idx = loadIdx(m), keys = Object.keys(idx).filter(function (k) { return m.texts[k]; });
      if (!keys.length) return;
      return Promise.all(keys.map(function (k) {
        var ch = chosenOf(m, k, idx[k]);
        return (ch.indexOf('search') >= 0 ? searchPart(k) : Promise.resolve(null)).then(function (sp) {
          // search wanted but unreachable now: keep its saved files as they are
          if (ch.indexOf('search') >= 0 && !sp) return { k: k, files: need(m, k, lanes(m, k), ch), keepSearch: true };
          return { k: k, files: need(m, k, lanes(m, k).concat(sp ? [sp] : []), ch) };
        });
      })).then(function (plan) {
        return caches.open(m.saved).then(function (cache) {
          var want = {}, have = {};
          plan.forEach(function (p) {
            p.files.forEach(function (r) { want[r[0]] = r; });
            Object.keys(idx[p.k].files || {}).forEach(function (f) { have[f] = idx[p.k].files[f]; if (p.keepSearch && f.indexOf(SEARCH) === 0) want[f] = [f, 0, have[f], 'keep']; });
          });
          var stale = Object.keys(want).filter(function (f) { return !want[f][3] && (have[f] !== want[f][2] || want[f][2] === ''); }).map(function (f) { return want[f]; });
          var dropped = Object.keys(have).filter(function (f) { return !want[f]; });
          return fetchInto(cache, stale).then(function () {
            return Promise.all(dropped.map(function (f) { return cache.delete(abs(f)); }));
          }).then(function () {
            plan.forEach(function (p) {
              var h = {}; p.files.forEach(function (r) { h[r[0]] = r[2]; });
              if (p.keepSearch) Object.keys(idx[p.k].files || {}).forEach(function (f) { if (f.indexOf(SEARCH) === 0) h[f] = idx[p.k].files[f]; });
              idx[p.k].files = h; idx[p.k].parts = chosenOf(m, p.k, idx[p.k]); idx[p.k].title = m.texts[p.k].title;
              if (!p.keepSearch) idx[p.k].bytes = sizeOf(p.files);
            });
            saveIdx(m, idx);
          });
        });
      });
    }).catch(function () {}).then(function () { refreshing = null; });
    return refreshing;
  }

  // ---- the save dialog: the text (always) + a checkbox per separate commentary + search, sizes and a running total ----
  var DCSS = '.vvoff-bg{position:fixed;inset:0;z-index:2100;background:rgba(0,0,0,.35);display:flex;align-items:center;justify-content:center;padding:12px}'
    + '.vvoff{background:var(--card,#fff);color:var(--ink,#222);border:1px solid var(--line,#ddd);border-radius:12px;box-shadow:0 12px 36px rgba(0,0,0,.25);width:min(420px,96vw);max-height:92vh;overflow-y:auto;box-sizing:border-box;padding:14px 16px;font:14px/1.4 system-ui,-apple-system,sans-serif}'
    + '.vvoff h3{margin:0 0 2px;font-size:16px}.vvoff .sub{color:var(--muted,#7a6a55);font-size:12.5px;margin-bottom:10px}'
    + '.vvoff label{display:flex;gap:9px;align-items:flex-start;padding:6px 2px;cursor:pointer}.vvoff label.fixed{cursor:default}'
    + '.vvoff label input{margin-top:3px;flex:none}.vvoff label span{flex:1}.vvoff .sz{color:var(--muted,#7a6a55);font-size:12.5px;white-space:nowrap}'
    + '.vvoff .dev{font-family:"Noto Serif Devanagari",serif;font-size:15px}'
    + '.vvoff .grp{font-size:11px;font-weight:700;letter-spacing:.05em;text-transform:uppercase;color:var(--muted,#7a6a55);margin:8px 2px 0}'
    + '.vvoff .tot{border-top:1px solid var(--line,#e5ded0);margin-top:8px;padding-top:8px;font-weight:600}'
    + '.vvoff .msg{color:var(--muted,#7a6a55);font-size:12.5px;min-height:1.2em;margin-top:4px}'
    + '.vvoff .btns{display:flex;gap:8px;justify-content:flex-end;flex-wrap:wrap;margin-top:10px}'
    + '.vvoff button{font:inherit;padding:6px 14px;border-radius:7px;border:1px solid var(--line,#d6d3d1);background:none;color:inherit;cursor:pointer}'
    + '.vvoff button.go{background:#b45309;border-color:#b45309;color:#fff}.vvoff button.rm{margin-right:auto;color:#b91c1c}.vvoff button[disabled]{opacity:.55;cursor:default}';
  // opens the dialog for `key` (default: this page's text). onDone(state) after a save / remove: state = 'saved' | 'removed'.
  function chooser(key, onDone) {
    if (!supported()) return;
    if (!document.getElementById('vvoff-css')) { var st = document.createElement('style'); st.id = 'vvoff-css'; st.textContent = DCSS; document.head.appendChild(st); }
    var bg = document.createElement('div'); bg.className = 'vvoff-bg';
    bg.innerHTML = '<div class="vvoff" role="dialog" aria-modal="true"><div class="msg">Loading…</div></div>';
    document.body.appendChild(bg);
    var box = bg.firstChild, busy = false;
    function close() { if (!busy) { bg.remove(); document.removeEventListener('keydown', onKey); } }
    function onKey(e) { if (e.key === 'Escape') close(); }
    document.addEventListener('keydown', onKey);
    bg.addEventListener('mousedown', function (e) { if (e.target === bg) close(); });
    manifest().then(function (m) {
      key = key || textOfPage(m);
      if (!key || !m.texts[key]) { box.innerHTML = '<div class="msg">This page cannot be saved for offline reading.</div><div class="btns"><button type="button" class="x">Close</button></div>'; box.querySelector('.x').onclick = close; return; }
      return partsOf(m, key).then(function (parts) {
        var t = m.texts[key], idx = loadIdx(m), rec = idx[key], chosen = rec ? chosenOf(m, key, rec) : parts.map(function (p) { return p.id; });
        var base = sizeOf(t.files.concat(m.shell)), lanesP = parts.filter(function (p) { return p.id !== 'search'; }), sp = parts.filter(function (p) { return p.id === 'search'; })[0];
        var row = function (p) { return '<label><input type="checkbox" data-p="' + esc(p.id) + '"' + (chosen.indexOf(p.id) >= 0 ? ' checked' : '') + '><span' + (p.id === 'search' ? '' : ' class="dev"') + '>' + esc(p.label) + '</span><span class="sz">' + mb(sizeOf(p.files)) + '</span></label>'; };
        box.innerHTML = '<h3>' + (rec ? 'Saved for offline' : 'Save for offline') + '</h3><div class="sub">' + esc(t.title) + (rec ? ' · choose what stays on this device' : ' · choose what to keep on this device') + '</div>'
          + '<label class="fixed"><input type="checkbox" checked disabled><span>The text, with the commentaries shown in its pages</span><span class="sz">' + mb(base) + '</span></label>'
          + (lanesP.length ? '<div class="grp">Commentaries loaded separately</div>' + lanesP.map(row).join('') : '')
          + (sp ? '<div class="grp">Search</div>' + row(sp) : (navigator.onLine ? '' : '<div class="msg">Search within this text can be added when you are online.</div>'))
          + '<div class="tot">About <span class="sum"></span> on this device</div><div class="msg st"></div>'
          + '<div class="btns">' + (rec ? '<button type="button" class="rm">Remove</button>' : '') + '<button type="button" class="x">Cancel</button><button type="button" class="go">' + (rec ? 'Update' : 'Save') + '</button></div>';
        var boxes = [].slice.call(box.querySelectorAll('input[data-p]')), go = box.querySelector('.go'), msg = box.querySelector('.st');
        function picked() { return boxes.filter(function (b) { return b.checked; }).map(function (b) { return b.getAttribute('data-p'); }); }
        function sum() { var c = picked(); box.querySelector('.sum').textContent = mb(base + parts.reduce(function (n, p) { return n + (c.indexOf(p.id) >= 0 ? sizeOf(p.files) : 0); }, 0)); }
        boxes.forEach(function (b) { b.addEventListener('change', sum); }); sum();
        box.querySelector('.x').onclick = close;
        var rm = box.querySelector('.rm');
        if (rm) rm.onclick = function () {
          if (!confirm('Remove “' + t.title + '” from this device? You can save it again any time.')) return;
          busy = true; remove(key).then(function () { busy = false; close(); if (onDone) onDone('removed'); });
        };
        go.onclick = function () {
          if (!navigator.onLine) { msg.textContent = 'You are offline — connect to the internet to save.'; return; }
          var c = picked();
          // search was saved but is unreachable right now (so it is not in `parts`): keep it chosen rather than drop it
          if (!sp && rec && chosen.indexOf('search') >= 0) c.push('search');
          busy = true; go.disabled = true; boxes.forEach(function (b) { b.disabled = true; }); if (rm) rm.disabled = true; box.querySelector('.x').disabled = true;
          save(key, c, function (done, total) { msg.textContent = 'Saving… ' + Math.floor(100 * done / Math.max(total, 1)) + '% · keep this page open'; })
            .then(function () { busy = false; close(); if (onDone) onDone('saved'); }, function (err) {
              busy = false; go.disabled = false; boxes.forEach(function (b) { b.disabled = false; }); if (rm) rm.disabled = false; box.querySelector('.x').disabled = false;
              msg.textContent = 'Could not save — try again (' + ((err && err.message) || 'network error') + ')'; });
        };
        go.focus();
      });
    }).catch(function () { box.innerHTML = '<div class="msg">Offline reading isn’t available on this site.</div><div class="btns"><button type="button" class="x">Close</button></div>'; box.querySelector('.x').onclick = close; });
  }
  // reading pages register the service worker too (it used to be registered only by the homepage) — so a reader who arrives
  // straight on a reading page, e.g. from a shared link, still gets offline copies. No auto-reload here (index.html does that).
  function register() {
    if (!supported()) return;
    try { navigator.serviceWorker.register(BASE + 'sw.js', { updateViaCache: 'none' }).catch(function () {}); } catch (e) {}   // (storage.persist: vv-store.js)
  }
  window.VVOffline = { supported: supported, manifest: manifest, info: info, save: save, remove: remove, list: list, refresh: refresh, register: register, chooser: chooser, mb: mb };
})();
